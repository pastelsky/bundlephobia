#!/usr/bin/env node

/**
 * Fetch official Google crawler & fetcher IP ranges and update HAProxy network list.
 *
 * Sources:
 *   - https://developers.google.com/search/apis/ipranges/googlebot.json
 *   - https://developers.google.com/search/apis/ipranges/special-crawlers.json
 *   - https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const SOURCES = [
  'https://developers.google.com/search/apis/ipranges/googlebot.json',
  'https://developers.google.com/search/apis/ipranges/special-crawlers.json',
  'https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json',
];

const DEFAULT_REPO_OUTPUT = path.resolve(__dirname, '..', 'google-crawler-networks.lst');
const SYSTEM_HAPROXY_PATH = '/etc/haproxy/google-crawler-networks.lst';

function parseIpv4(cidr) {
  const [ipStr, maskStr] = cidr.split('/');
  const mask = Number(maskStr);
  const parts = ipStr.split('.').map(Number);
  const ip = ((parts[0] << 24) | (parts[1] << 16) | (parts[2] << 8) | parts[3]) >>> 0;
  const size = 2 ** (32 - mask);
  const start = (ip & ~((size - 1) >>> 0)) >>> 0;
  const end = (start + size - 1) >>> 0;
  return { start: BigInt(start), end: BigInt(end), version: 4 };
}

function parseIpv6(cidr) {
  const [ipStr, maskStr] = cidr.split('/');
  const mask = Number(maskStr);
  let [left, right] = ipStr.split('::');
  let groups = [];
  if (right !== undefined) {
    const leftGroups = left ? left.split(':') : [];
    const rightGroups = right ? right.split(':') : [];
    const missing = 8 - (leftGroups.length + rightGroups.length);
    groups = [...leftGroups, ...Array(missing).fill('0'), ...rightGroups];
  } else {
    groups = left.split(':');
  }
  let ip = 0n;
  for (const g of groups) {
    ip = (ip << 16n) | BigInt(parseInt(g || '0', 16));
  }
  const size = 1n << BigInt(128 - mask);
  const maskBits = ((1n << 128n) - 1n) ^ (size - 1n);
  const start = ip & maskBits;
  const end = start + size - 1n;
  return { start, end, version: 6 };
}

function intToIpv4(ip) {
  const n = Number(ip);
  return [(n >>> 24) & 255, (n >>> 16) & 255, (n >>> 8) & 255, n & 255].join('.');
}

function intToIpv6(ip) {
  const hex = ip.toString(16).padStart(32, '0');
  const groups = [];
  for (let i = 0; i < 32; i += 4) {
    groups.push(hex.slice(i, i + 4).replace(/^0+/, '') || '0');
  }
  return groups.join(':').replace(/(^|:)0(:0)+(:|$)/, '::');
}

function intervalToCidrs(start, end, version) {
  const maxBits = version === 4 ? 32 : 128;
  const maxBig = BigInt(maxBits);
  const cidrs = [];
  let curr = start;

  while (curr <= end) {
    const remaining = end - curr + 1n;
    let maxSize = 1n;
    while (maxSize * 2n <= remaining && curr % (maxSize * 2n) === 0n) {
      maxSize *= 2n;
    }
    let mask = maxBig;
    let s = maxSize;
    while (s > 1n) {
      s >>= 1n;
      mask -= 1n;
    }
    const ipStr = version === 4 ? intToIpv4(curr) : intToIpv6(curr);
    cidrs.push(`${ipStr}/${mask}`);
    curr += maxSize;
  }
  return cidrs;
}

function collapseRanges(ranges, version) {
  if (ranges.length === 0) return [];
  ranges.sort((a, b) => (a.start < b.start ? -1 : a.start > b.start ? 1 : 0));
  const merged = [ranges[0]];
  for (let i = 1; i < ranges.length; i++) {
    const last = merged[merged.length - 1];
    const curr = ranges[i];
    if (curr.start <= last.end + 1n) {
      if (curr.end > last.end) last.end = curr.end;
    } else {
      merged.push({ start: curr.start, end: curr.end });
    }
  }
  const result = [];
  for (const m of merged) {
    result.push(...intervalToCidrs(m.start, m.end, version));
  }
  return result;
}

async function fetchGoogleRanges() {
  const v4 = [];
  const v6 = [];

  for (const url of SOURCES) {
    const res = await fetch(url, {
      headers: { 'User-Agent': 'bundlephobia-sync/1.0' },
      signal: AbortSignal.timeout(15000),
    });
    if (!res.ok) {
      throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
    }
    const data = await res.json();
    for (const prefix of data.prefixes || []) {
      if (prefix.ipv4Prefix) v4.push(parseIpv4(prefix.ipv4Prefix));
      if (prefix.ipv6Prefix) v6.push(parseIpv6(prefix.ipv6Prefix));
    }
  }

  const v4Collapsed = collapseRanges(v4, 4);
  const v6Collapsed = collapseRanges(v6, 6);
  return { v4: v4Collapsed, v6: v6Collapsed };
}

function generateFileContent(v4, v6) {
  const lines = [
    '# Google Official Crawler & Fetcher IP Ranges',
    '# Auto-generated by operations/haproxy/scripts/sync-google-crawlers.js',
    '# Sources:',
  ];
  for (const url of SOURCES) {
    lines.push(`#   - ${url}`);
  }
  lines.push('# IPv4');
  for (const net of v4) {
    lines.push(net);
  }
  lines.push('# IPv6');
  for (const net of v6) {
    lines.push(net);
  }
  lines.push('');
  return lines.join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const installToSystem = args.includes('--install');
  const reloadHaproxy = args.includes('--reload');
  const outArgIdx = args.indexOf('--output');
  const outputPath = outArgIdx !== -1 && args[outArgIdx + 1] ? args[outArgIdx + 1] : DEFAULT_REPO_OUTPUT;

  console.log(`[${new Date().toISOString()}] Fetching Google crawler ranges from ${SOURCES.length} sources...`);
  const { v4, v6 } = await fetchGoogleRanges();
  console.log(`Discovered ${v4.length} IPv4 CIDRs and ${v6.length} IPv6 CIDRs.`);

  const newContent = generateFileContent(v4, v6);

  let existingRepo = '';
  if (fs.existsSync(outputPath)) {
    existingRepo = fs.readFileSync(outputPath, 'utf8');
  }

  const hasRepoChanged = newContent !== existingRepo;
  if (hasRepoChanged) {
    fs.writeFileSync(outputPath, newContent, 'utf8');
    console.log(`Updated ${outputPath}`);
  } else {
    console.log(`${outputPath} is already up to date.`);
  }

  if (installToSystem) {
    let existingSystem = '';
    if (fs.existsSync(SYSTEM_HAPROXY_PATH)) {
      existingSystem = fs.readFileSync(SYSTEM_HAPROXY_PATH, 'utf8');
    }

    if (newContent !== existingSystem) {
      fs.writeFileSync(SYSTEM_HAPROXY_PATH, newContent, 'utf8');
      console.log(`Installed updated networks to ${SYSTEM_HAPROXY_PATH}`);

      if (reloadHaproxy) {
        console.log('Reloading HAProxy service...');
        execSync('systemctl reload haproxy', { stdio: 'inherit' });
        console.log('HAProxy reloaded successfully.');
      }
    } else {
      console.log(`${SYSTEM_HAPROXY_PATH} is already identical. No reload needed.`);
    }
  }
}

main().catch((err) => {
  console.error('Failed to sync Google crawler IP ranges:', err);
  process.exit(1);
});
