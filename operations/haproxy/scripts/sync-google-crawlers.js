#!/usr/bin/env node

/**
 * Fetch official Google crawler & fetcher IP ranges and update HAProxy network list.
 *
 * Sources:
 *   - https://developers.google.com/search/apis/ipranges/googlebot.json
 *   - https://developers.google.com/search/apis/ipranges/special-crawlers.json
 *   - https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json
 */

const fs = require('fs');

const { execSync } = require('child_process');

const SOURCES = [
  'https://developers.google.com/search/apis/ipranges/googlebot.json',
  'https://developers.google.com/search/apis/ipranges/special-crawlers.json',
  'https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json',
];

const TARGET_PATH = process.env.GOOGLE_NETWORKS_FILE || '/etc/haproxy/google-crawler-networks.lst';

async function fetchGooglePrefixes() {
  const { mergeCidr } = await import('cidr-tools');

  const prefixes = new Set();

  for (const url of SOURCES) {
    const res = await fetch(url, {
      headers: { 'User-Agent': 'bundlephobia-sync/1.0' },
      signal: AbortSignal.timeout(15000),
    });

    if (!res.ok) {
      throw new Error(`Failed to fetch ${url}: HTTP ${res.status}`);
    }

    const data = await res.json();

    for (const prefix of data.prefixes || []) {
      const cidr = prefix.ipv4Prefix || prefix.ipv6Prefix;

      if (cidr) {
        prefixes.add(cidr);
      }
    }
  }

  const merged = mergeCidr(Array.from(prefixes));

  const v4 = merged.filter((cidr) => !cidr.includes(':'));

  const v6 = merged.filter((cidr) => cidr.includes(':'));

  return { v4, v6 };
}

function generateFileContent(v4, v6) {
  const lines = [
    '# Google Official Crawler & Fetcher IP Ranges',
    '# Auto-generated by operations/haproxy/scripts/sync-google-crawlers.js',
    '# Sources:',
  ];

  for (const url of SOURCES) {
    lines.push(`#   - ${url}`);
  }

  lines.push('# IPv4');

  for (const net of v4) {
    lines.push(net);
  }

  lines.push('# IPv6');

  for (const net of v6) {
    lines.push(net);
  }

  lines.push('');

  return lines.join('\n');
}

function updateNetworksFile(newContent, reloadHaproxy) {
  let existingContent = '';

  if (fs.existsSync(TARGET_PATH)) {
    existingContent = fs.readFileSync(TARGET_PATH, 'utf8');
  }

  if (newContent === existingContent) {
    console.log(`${TARGET_PATH} is already up to date. No reload needed.`);

    return;
  }

  fs.writeFileSync(TARGET_PATH, newContent, 'utf8');

  console.log(`Updated ${TARGET_PATH}`);

  if (reloadHaproxy) {
    console.log('Reloading HAProxy service...');

    execSync('systemctl reload haproxy', { stdio: 'inherit' });

    console.log('HAProxy reloaded successfully.');
  }
}

async function main() {
  const args = process.argv.slice(2);

  const reloadHaproxy = args.includes('--reload');

  console.log(`[${new Date().toISOString()}] Fetching Google crawler ranges from ${SOURCES.length} sources...`);

  const { v4, v6 } = await fetchGooglePrefixes();

  console.log(`Discovered ${v4.length} IPv4 CIDRs and ${v6.length} IPv6 CIDRs.`);

  const newContent = generateFileContent(v4, v6);

  updateNetworksFile(newContent, reloadHaproxy);
}

main().catch((err) => {
  console.error('Failed to sync Google crawler IP ranges:', err);

  process.exit(1);
});
