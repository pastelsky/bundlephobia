#!/usr/bin/env python3
"""
Fetch official Google crawler and fetcher IP ranges and update HAProxy network list.
Sources:
  - https://developers.google.com/search/apis/ipranges/googlebot.json
  - https://developers.google.com/search/apis/ipranges/special-crawlers.json
  - https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json
"""

import argparse
import ipaddress
import json
import os
import sys
import urllib.request

SOURCES = [
    "https://developers.google.com/search/apis/ipranges/googlebot.json",
    "https://developers.google.com/search/apis/ipranges/special-crawlers.json",
    "https://developers.google.com/search/apis/ipranges/user-triggered-fetchers.json",
]


def fetch_ranges():
    v4_set, v6_set = set(), set()
    for url in SOURCES:
        req = urllib.request.Request(url, headers={"User-Agent": "bundlephobia-sync/1.0"})
        with urllib.request.urlopen(req, timeout=15) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            for prefix in data.get("prefixes", []):
                if "ipv4Prefix" in prefix:
                    v4_set.add(ipaddress.IPv4Network(prefix["ipv4Prefix"]))
                elif "ipv6Prefix" in prefix:
                    v6_set.add(ipaddress.IPv6Network(prefix["ipv6Prefix"]))

    v4_collapsed = sorted(list(ipaddress.collapse_addresses(v4_set)))
    v6_collapsed = sorted(list(ipaddress.collapse_addresses(v6_set)))
    return v4_collapsed, v6_collapsed


def main():
    parser = argparse.ArgumentParser(description="Sync Google crawler IP ranges for HAProxy")
    default_out = os.path.abspath(
        os.path.join(os.path.dirname(__file__), "..", "google-crawler-networks.lst")
    )
    parser.add_argument(
        "--output", "-o", default=default_out, help=f"Path to output file (default: {default_out})"
    )
    args = parser.parse_args()

    print(f"Fetching Google crawler IP ranges from {len(SOURCES)} sources...")
    v4, v6 = fetch_ranges()
    print(f"Discovered {len(v4)} IPv4 ranges and {len(v6)} IPv6 ranges.")

    content = [
        "# Google Official Crawler & Fetcher IP Ranges",
        "# Auto-generated by operations/haproxy/scripts/sync-google-crawlers.py",
        "# Sources:",
    ]
    for url in SOURCES:
        content.append(f"#   - {url}")
    content.append("# IPv4")
    for net in v4:
        content.append(str(net))
    content.append("# IPv6")
    for net in v6:
        content.append(str(net))
    content.append("")

    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(content))

    print(f"Updated {args.output} successfully.")


if __name__ == "__main__":
    main()
